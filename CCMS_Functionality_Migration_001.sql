CREATE OR REPLACE FUNCTION ccms_reject_audit_mutation() RETURNS TRIGGER AS $$
BEGIN RAISE EXCEPTION 'Audit records are append-only'; END;
$$ LANGUAGE plpgsql;
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname='trg_audit_log_append_only' AND tgrelid='public.audit_log'::regclass) THEN
        CREATE TRIGGER trg_audit_log_append_only BEFORE UPDATE OR DELETE ON audit_log
        FOR EACH ROW EXECUTE FUNCTION ccms_reject_audit_mutation();
    END IF;
END $$;

CREATE OR REPLACE FUNCTION ccms_reject_status_history_mutation() RETURNS TRIGGER AS $$
BEGIN RAISE EXCEPTION 'Case status history is append-only'; END;
$$ LANGUAGE plpgsql;
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname='trg_case_status_history_append_only' AND tgrelid='public.case_status_history'::regclass) THEN
        CREATE TRIGGER trg_case_status_history_append_only BEFORE UPDATE OR DELETE ON case_status_history
        FOR EACH ROW EXECUTE FUNCTION ccms_reject_status_history_mutation();
    END IF;
END $$;

DO $$ DECLARE tbl TEXT; trg TEXT; BEGIN
    FOR tbl,trg IN SELECT * FROM (VALUES
        ('auth_event_log','trg_auth_event_append_only'),
        ('notification_delivery_attempt','trg_notification_attempt_append_only'),
        ('agency_liaison_event','trg_agency_liaison_append_only'),
        ('case_transfer_history','trg_case_transfer_append_only')
    ) AS t(table_name,trigger_name) LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname=trg AND tgrelid=to_regclass('public.'||tbl)) THEN
            EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION ccms_reject_audit_mutation()',trg,tbl);
        END IF;
    END LOOP;
END $$;

CREATE OR REPLACE FUNCTION ccms_protect_archived_cases() RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP='DELETE' THEN
        RAISE EXCEPTION 'Case rows cannot be deleted; archive the case instead';
    END IF;
    IF OLD.archived_at IS NOT NULL THEN
        RAISE EXCEPTION 'Archived case records are immutable';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname='trg_case_archive_immutable' AND tgrelid='public.court_case'::regclass) THEN
        CREATE TRIGGER trg_case_archive_immutable BEFORE UPDATE OR DELETE ON court_case
        FOR EACH ROW EXECUTE FUNCTION ccms_protect_archived_cases();
    END IF;
END $$;

CREATE OR REPLACE FUNCTION ccms_protect_signed_orders() RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP='DELETE' AND OLD.digital_signature_hash IS NOT NULL THEN
        RAISE EXCEPTION 'Digitally signed orders are immutable';
    END IF;
    IF TG_OP='UPDATE' AND OLD.digital_signature_hash IS NOT NULL AND
       (NEW.order_type,NEW.order_content,NEW.digital_signature_hash,NEW.case_id,NEW.issued_by_judge_id,NEW.hearing_id,NEW.signed_at)
       IS DISTINCT FROM
       (OLD.order_type,OLD.order_content,OLD.digital_signature_hash,OLD.case_id,OLD.issued_by_judge_id,OLD.hearing_id,OLD.signed_at) THEN
        RAISE EXCEPTION 'Signed order content is immutable';
    END IF;
    IF TG_OP='DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname='trg_signed_order_immutable' AND tgrelid='public.court_order'::regclass) THEN
        CREATE TRIGGER trg_signed_order_immutable BEFORE UPDATE OR DELETE ON court_order
        FOR EACH ROW EXECUTE FUNCTION ccms_protect_signed_orders();
    END IF;
END $$;

CREATE OR REPLACE FUNCTION ccms_protect_signed_judgments() RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP='DELETE' AND OLD.digital_signature_hash IS NOT NULL THEN
        RAISE EXCEPTION 'Digitally signed judgments are immutable';
    END IF;
    IF TG_OP='UPDATE' AND OLD.digital_signature_hash IS NOT NULL AND
       (NEW.pronouncement_date,NEW.verdict_text,NEW.digital_signature_hash,NEW.case_id,NEW.signed_at)
       IS DISTINCT FROM
       (OLD.pronouncement_date,OLD.verdict_text,OLD.digital_signature_hash,OLD.case_id,OLD.signed_at) THEN
        RAISE EXCEPTION 'Signed judgment content is immutable';
    END IF;
    IF TG_OP='DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname='trg_signed_judgment_immutable' AND tgrelid='public.judgment'::regclass) THEN
        CREATE TRIGGER trg_signed_judgment_immutable BEFORE UPDATE OR DELETE ON judgment
        FOR EACH ROW EXECUTE FUNCTION ccms_protect_signed_judgments();
    END IF;
END $$;

