    role_id INTEGER NOT NULL REFERENCES role(role_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    permission_id INTEGER NOT NULL REFERENCES app_permission(permission_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    PRIMARY KEY (role_id, permission_id)
