-- -------------------------
-- Derived view: current case status
-- -------------------------

CREATE OR REPLACE VIEW case_current_status AS
SELECT
    c.case_id,
    c.cuid,
    c.cnr,
    c.case_title,
    latest.new_status AS case_status,
    latest.transition_timestamp
FROM court_case AS c
LEFT JOIN LATERAL (
    SELECT h.new_status, h.transition_timestamp
    FROM case_status_history AS h
    WHERE h.case_id = c.case_id
    ORDER BY h.transition_timestamp DESC
    LIMIT 1
) AS latest ON TRUE;

