    h.hearing_id, h.case_id, c.cnr, c.case_title,
    h.forum_id, f.forum_name,
    h.bench_id, b.bench_name,
    h.courtroom_id, cr.room_code,
    h.hearing_date, h.start_time, h.end_time,
    h.hearing_purpose, h.hearing_status
FROM hearing h
JOIN case_file c ON c.case_id = h.case_id
JOIN forum f ON f.forum_id = h.forum_id
LEFT JOIN bench b ON b.bench_id = h.bench_id
LEFT JOIN courtroom cr ON cr.courtroom_id = h.courtroom_id
WHERE h.hearing_date >= CURRENT_DATE
  AND h.hearing_status = 'SCHEDULED';

