CREATE VIEW v_case_disposal_time AS
SELECT
    c.case_id, c.cnr, c.case_title, c.filing_date,
    MIN(j.pronouncement_date) FILTER (WHERE j.is_final = TRUE) AS first_final_judgment_date,
    (MIN(j.pronouncement_date) FILTER (WHERE j.is_final = TRUE) - c.filing_date) AS days_to_first_final_judgment
FROM case_file c
LEFT JOIN court_order co ON co.case_id = c.case_id
LEFT JOIN judgment j ON j.order_id = co.order_id
GROUP BY c.case_id, c.cnr, c.case_title, c.filing_date;

CREATE VIEW v_case_adjournment_summary AS
SELECT
    c.case_id, c.cnr, c.case_title,
    COUNT(DISTINCT h.hearing_id) AS total_scheduled_hearings,
    COUNT(DISTINCT ar.adjournment_id) AS total_adjournment_requests,
    COUNT(DISTINCT ar.adjournment_id) FILTER (WHERE ar.decision_status = 'APPROVED') AS approved_adjournments,
    COUNT(DISTINCT ar.adjournment_id) FILTER (WHERE ar.decision_status = 'REJECTED') AS rejected_adjournments,
    COUNT(DISTINCT ar.adjournment_id) FILTER (WHERE ar.decision_status = 'PENDING') AS pending_adjournments
FROM case_file c
LEFT JOIN hearing h ON h.case_id = c.case_id
LEFT JOIN adjournment_request ar ON ar.hearing_id = h.hearing_id
GROUP BY c.case_id, c.cnr, c.case_title;

CREATE VIEW v_outstanding_case_fees AS
SELECT
    cf.case_id, c.cnr, c.case_title,
    SUM(GREATEST(cf.amount_due - cf.waiver_amount - COALESCE(paid.total_paid, 0), 0)) AS outstanding_amount
FROM case_fee cf
JOIN case_file c ON c.case_id = cf.case_id
LEFT JOIN (
    SELECT case_fee_id, SUM(amount_paid) AS total_paid
    FROM payment
    WHERE payment_status = 'SUCCESS'
    GROUP BY case_fee_id
) paid ON paid.case_fee_id = cf.case_fee_id
WHERE cf.fee_status NOT IN ('WAIVED','CANCELLED')
GROUP BY cf.case_id, c.cnr, c.case_title;

CREATE VIEW v_judge_upcoming_hearing_load AS
SELECT
    jp.judge_id, p.full_name AS judge_name,
    COUNT(DISTINCT h.hearing_id) AS upcoming_hearings
FROM judge_profile jp
JOIN person p ON p.person_id = jp.person_id
LEFT JOIN judge_bench_assignment jba ON jba.judge_id = jp.judge_id
    AND jba.start_date <= CURRENT_DATE
    AND (jba.end_date IS NULL OR jba.end_date >= CURRENT_DATE)
LEFT JOIN hearing h ON h.bench_id = jba.bench_id
    AND h.hearing_date >= CURRENT_DATE
    AND h.hearing_status = 'SCHEDULED'
GROUP BY jp.judge_id, p.full_name;

