CREATE TABLE case_fee (
    case_fee_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT NOT NULL REFERENCES case_file(case_id) ON DELETE RESTRICT,
    filing_id BIGINT REFERENCES case_filing(filing_id) ON DELETE RESTRICT,
    fee_type_code VARCHAR(40) NOT NULL REFERENCES fee_type(fee_type_code),
    amount_due NUMERIC(14,2) NOT NULL CHECK (amount_due >= 0),
    due_date DATE,
    waiver_amount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (waiver_amount >= 0),
    fee_status VARCHAR(30) NOT NULL DEFAULT 'DUE'
        CHECK (fee_status IN ('DUE','PARTIALLY_PAID','PAID','WAIVED','CANCELLED')),
    assessed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    notes TEXT,
    CHECK (waiver_amount <= amount_due)
);

CREATE TABLE payment (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_fee_id BIGINT NOT NULL REFERENCES case_fee(case_fee_id) ON DELETE RESTRICT,
    amount_paid NUMERIC(14,2) NOT NULL CHECK (amount_paid > 0),
    payment_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    payment_method VARCHAR(40) NOT NULL CHECK (payment_method IN
        ('CASH','CARD','BANK_TRANSFER','UPI','CHEQUE','ONLINE_GATEWAY','OTHER')),
    transaction_reference VARCHAR(160),
    payment_status VARCHAR(30) NOT NULL DEFAULT 'SUCCESS'
        CHECK (payment_status IN ('PENDING','SUCCESS','FAILED','REFUNDED')),
    received_by_user_id BIGINT REFERENCES user_account(user_id) ON DELETE SET NULL,
    UNIQUE (transaction_reference)
);

