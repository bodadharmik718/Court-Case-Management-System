-- ---------------------------------------------------------------------------
-- 10. COURT ORDERS, JUDGMENTS, APPEALS AND CASE LAW REFERENCES
-- Orders and judgments are distinct, but a judgment may reference its formal
-- order record. There may be multiple interim/final/corrected judgments over
-- a case's life; do not impose one judgment per case.
-- ---------------------------------------------------------------------------

CREATE TABLE court_order (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT NOT NULL REFERENCES case_file(case_id) ON DELETE RESTRICT,
    hearing_id BIGINT REFERENCES hearing(hearing_id) ON DELETE SET NULL,
    issuing_forum_id BIGINT NOT NULL REFERENCES forum(forum_id) ON DELETE RESTRICT,
    order_type_code VARCHAR(50) NOT NULL REFERENCES court_order_type(order_type_code),
    order_number VARCHAR(100),
    order_year SMALLINT CHECK (order_year IS NULL OR order_year BETWEEN 1900 AND 2200),
    order_date DATE NOT NULL,
    order_title VARCHAR(400),
    order_text TEXT,
    order_status VARCHAR(30) NOT NULL DEFAULT 'DRAFT'
        CHECK (order_status IN ('DRAFT','SIGNED','PRONOUNCED','PUBLISHED','SUPERSEDED','WITHDRAWN')),
    digital_signature_hash VARCHAR(256),
    created_by_user_id BIGINT REFERENCES user_account(user_id) ON DELETE SET NULL,
    UNIQUE (issuing_forum_id, order_year, order_number),
    CHECK ((order_number IS NULL AND order_year IS NULL) OR
           (order_number IS NOT NULL AND order_year IS NOT NULL))
);

CREATE TABLE court_order_judge (
    order_id BIGINT NOT NULL REFERENCES court_order(order_id) ON DELETE RESTRICT,
    judge_id BIGINT NOT NULL REFERENCES judge_profile(judge_id) ON DELETE RESTRICT,
    judge_role VARCHAR(50) NOT NULL DEFAULT 'PRESIDING',
    PRIMARY KEY (order_id, judge_id, judge_role)
);

CREATE TABLE judgment (
    judgment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT UNIQUE REFERENCES court_order(order_id) ON DELETE RESTRICT,
    judgment_type VARCHAR(40) NOT NULL CHECK (judgment_type IN
        ('INTERIM','FINAL','PARTIAL','REVIEW','CORRECTED','OTHER')),
    pronouncement_date DATE NOT NULL,
    is_final BOOLEAN NOT NULL DEFAULT FALSE,
    verdict_summary TEXT,
    full_text TEXT,
    digital_signature_hash VARCHAR(256),
    publication_status VARCHAR(30) NOT NULL DEFAULT 'UNPUBLISHED'
        CHECK (publication_status IN ('UNPUBLISHED','PUBLISHED','REDACTED','SEALED'))
);

CREATE TABLE order_document (
    order_id BIGINT NOT NULL REFERENCES court_order(order_id) ON DELETE RESTRICT,
    document_id BIGINT NOT NULL REFERENCES document(document_id) ON DELETE RESTRICT,
    PRIMARY KEY (order_id, document_id)
);

CREATE TABLE appeal_detail (
    appeal_case_id BIGINT PRIMARY KEY REFERENCES case_file(case_id) ON DELETE RESTRICT,
    original_case_id BIGINT NOT NULL REFERENCES case_file(case_id) ON DELETE RESTRICT,
