-- ---------------------------------------------------------------------------
-- 14. AUTOMATIC INITIAL CASE STATUS
-- The first status event is created when a case record is inserted. Further
-- status changes must be INSERTs into CASE_STATUS_HISTORY, never overwrites.
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION ccms_add_initial_case_status()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO case_status_history (case_id, status_code, changed_at, changed_by_user_id, remarks)
    VALUES (NEW.case_id, 'FILED', NEW.created_at, NEW.created_by_user_id, 'Initial case status');
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_case_initial_status
AFTER INSERT ON case_file
FOR EACH ROW EXECUTE FUNCTION ccms_add_initial_case_status();

-- Guard status history against invalid jumps. The application should still
-- begin the transaction by locking the case row before recording a transition.
CREATE OR REPLACE FUNCTION ccms_validate_case_status_transition()
RETURNS TRIGGER AS $$
DECLARE
    v_current_status VARCHAR(40);
BEGIN
    PERFORM 1 FROM case_file WHERE case_id = NEW.case_id FOR UPDATE;

    SELECT status_code INTO v_current_status
    FROM case_status_history
    WHERE case_id = NEW.case_id
    ORDER BY changed_at DESC, case_status_history_id DESC
    LIMIT 1;

    IF v_current_status IS NULL THEN
        IF NEW.status_code <> 'FILED' THEN
            RAISE EXCEPTION 'The first status for a case must be FILED';
        END IF;
    ELSIF NOT EXISTS (
        SELECT 1 FROM case_status_transition
        WHERE from_status_code = v_current_status
          AND to_status_code = NEW.status_code
    ) THEN
        RAISE EXCEPTION 'Invalid case status transition: % -> %',
            v_current_status, NEW.status_code;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_validate_case_status_transition
BEFORE INSERT ON case_status_history
FOR EACH ROW EXECUTE FUNCTION ccms_validate_case_status_transition();

-- Keep the current forum on CASE_FILE synchronized with the transfer history.
CREATE OR REPLACE FUNCTION ccms_validate_case_transfer()
RETURNS TRIGGER AS $$
DECLARE
    v_current_forum_id BIGINT;
BEGIN
    SELECT current_forum_id INTO v_current_forum_id
    FROM case_file
    WHERE case_id = NEW.case_id
    FOR UPDATE;

    IF v_current_forum_id IS NULL THEN
        RAISE EXCEPTION 'Case % does not exist', NEW.case_id;
    END IF;
    IF v_current_forum_id <> NEW.from_forum_id THEN
        RAISE EXCEPTION 'Transfer source does not match the case current forum';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION ccms_apply_case_transfer()
RETURNS TRIGGER AS $$
BEGIN
    UPDATE case_file
    SET current_forum_id = NEW.to_forum_id,
        updated_at = CURRENT_TIMESTAMP
    WHERE case_id = NEW.case_id;

    INSERT INTO case_status_history
        (case_id, status_code, changed_at, changed_by_user_id, remarks)
    VALUES
        (NEW.case_id, 'TRANSFERRED', NEW.recorded_at, NEW.approved_by_user_id,
         'Case transferred to forum ID ' || NEW.to_forum_id::TEXT);

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_validate_case_transfer
BEFORE INSERT ON case_transfer
FOR EACH ROW EXECUTE FUNCTION ccms_validate_case_transfer();

CREATE TRIGGER trg_apply_case_transfer
AFTER INSERT ON case_transfer
FOR EACH ROW EXECUTE FUNCTION ccms_apply_case_transfer();

