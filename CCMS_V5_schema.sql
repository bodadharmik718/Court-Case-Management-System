-- ============================================================================
-- CCMS V5 - Judiciary / Court Case Management System
-- Database: PostgreSQL 14+
-- Scope: India-oriented, configurable for multiple courts, tribunals and forums
-- Created as a fresh-schema script. Run inside an empty project database.
--
-- IMPORTANT:
--   1. Create the PostgreSQL database first (for example: ccms_db).
--   2. Connect to that database and execute this complete script.
--   3. Do not store uploaded file bytes in these tables. Store files in protected
--      file/object storage and save the storage key in DOCUMENT_VERSION.
--   4. The application must write history rows in the same transaction as the
--      corresponding business change (transfer, representation, status, etc.).
-- ============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. REFERENCE / CONFIGURATION TABLES
-- ---------------------------------------------------------------------------

CREATE TABLE forum_type (
    forum_type_code VARCHAR(40) PRIMARY KEY,
    forum_type_name VARCHAR(120) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE forum_relationship_type (
    relationship_type_code VARCHAR(40) PRIMARY KEY,
    relationship_name VARCHAR(120) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE jurisdiction_area (
    area_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_area_id BIGINT REFERENCES jurisdiction_area(area_id) ON DELETE RESTRICT,
    area_type VARCHAR(30) NOT NULL CHECK (area_type IN
        ('COUNTRY','STATE','DISTRICT','SUB_DISTRICT','CITY','LOCAL_AREA','OTHER')),
    area_code VARCHAR(50),
    area_name VARCHAR(160) NOT NULL,
    UNIQUE (parent_area_id, area_type, area_name)
);

CREATE TABLE subject_matter (
    subject_matter_code VARCHAR(50) PRIMARY KEY,
    subject_matter_name VARCHAR(120) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE case_category (
    category_code VARCHAR(40) PRIMARY KEY,
    category_name VARCHAR(120) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE case_type (
    case_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_code VARCHAR(40) NOT NULL REFERENCES case_category(category_code),
    parent_case_type_id BIGINT REFERENCES case_type(case_type_id) ON DELETE RESTRICT,
    case_type_code VARCHAR(50) NOT NULL UNIQUE,
    case_type_name VARCHAR(160) NOT NULL,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE case_status (
    status_code VARCHAR(40) PRIMARY KEY,
    status_name VARCHAR(120) NOT NULL UNIQUE,
    is_terminal BOOLEAN NOT NULL DEFAULT FALSE,
    description TEXT
);

CREATE TABLE case_status_transition (
    from_status_code VARCHAR(40) NOT NULL REFERENCES case_status(status_code) ON DELETE RESTRICT,
    to_status_code VARCHAR(40) NOT NULL REFERENCES case_status(status_code) ON DELETE RESTRICT,
    requires_approval BOOLEAN NOT NULL DEFAULT FALSE,
    transition_notes TEXT,
    PRIMARY KEY (from_status_code, to_status_code),
    CHECK (from_status_code <> to_status_code)
);

CREATE TABLE case_party_role (
    party_role_code VARCHAR(40) PRIMARY KEY,
    role_name VARCHAR(120) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE case_relationship_type (
    relationship_type_code VARCHAR(40) PRIMARY KEY,
    relationship_name VARCHAR(120) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE filing_type (
    filing_type_code VARCHAR(50) PRIMARY KEY,
    filing_type_name VARCHAR(120) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE filing_status (
    filing_status_code VARCHAR(40) PRIMARY KEY,
    filing_status_name VARCHAR(120) NOT NULL UNIQUE,
    is_terminal BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE evidence_type (
    evidence_type_code VARCHAR(50) PRIMARY KEY,
    evidence_type_name VARCHAR(120) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE court_order_type (
    order_type_code VARCHAR(50) PRIMARY KEY,
    order_type_name VARCHAR(120) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE document_type (
    document_type_code VARCHAR(50) PRIMARY KEY,
    document_type_name VARCHAR(120) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE fee_type (
    fee_type_code VARCHAR(40) PRIMARY KEY,
    fee_type_name VARCHAR(120) NOT NULL UNIQUE,
    description TEXT
);

-- ---------------------------------------------------------------------------
-- 2. COURT / FORUM NETWORK AND JURISDICTION
-- A forum may be a court, tribunal, commission, Lok Adalat, etc.
-- Administrative and appellate relationships are stored separately; they are
-- not assumed to be the same hierarchy.
-- ---------------------------------------------------------------------------

CREATE TABLE forum (
    forum_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    forum_code VARCHAR(60) NOT NULL UNIQUE,
    forum_name VARCHAR(220) NOT NULL,
    forum_type_code VARCHAR(40) NOT NULL REFERENCES forum_type(forum_type_code),
    parent_forum_id BIGINT REFERENCES forum(forum_id) ON DELETE RESTRICT,
    state_name VARCHAR(120),
    district_name VARCHAR(120),
    address TEXT,
    phone VARCHAR(40),
    email VARCHAR(254),
    established_on DATE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (parent_forum_id IS NULL OR parent_forum_id <> forum_id)
);

CREATE TABLE forum_relationship (
    forum_relationship_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_forum_id BIGINT NOT NULL REFERENCES forum(forum_id) ON DELETE RESTRICT,
    to_forum_id BIGINT NOT NULL REFERENCES forum(forum_id) ON DELETE RESTRICT,
    relationship_type_code VARCHAR(40) NOT NULL
        REFERENCES forum_relationship_type(relationship_type_code),
    valid_from DATE NOT NULL DEFAULT CURRENT_DATE,
    valid_to DATE,
    notes TEXT,
    CHECK (from_forum_id <> to_forum_id),
    CHECK (valid_to IS NULL OR valid_to >= valid_from),
    UNIQUE (from_forum_id, to_forum_id, relationship_type_code, valid_from)
);

CREATE TABLE forum_territorial_jurisdiction (
    forum_id BIGINT NOT NULL REFERENCES forum(forum_id) ON DELETE RESTRICT,
    area_id BIGINT NOT NULL REFERENCES jurisdiction_area(area_id) ON DELETE RESTRICT,
    valid_from DATE NOT NULL DEFAULT CURRENT_DATE,
    valid_to DATE,
    notes TEXT,
    PRIMARY KEY (forum_id, area_id, valid_from),
    CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

CREATE TABLE forum_subject_jurisdiction (
    forum_id BIGINT NOT NULL REFERENCES forum(forum_id) ON DELETE RESTRICT,
    subject_matter_code VARCHAR(50) NOT NULL REFERENCES subject_matter(subject_matter_code),
    valid_from DATE NOT NULL DEFAULT CURRENT_DATE,
    valid_to DATE,
    notes TEXT,
    PRIMARY KEY (forum_id, subject_matter_code, valid_from),
    CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

CREATE TABLE courtroom (
    courtroom_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    forum_id BIGINT NOT NULL REFERENCES forum(forum_id) ON DELETE RESTRICT,
    room_code VARCHAR(50) NOT NULL,
    room_name VARCHAR(120),
    floor_number VARCHAR(30),
    capacity INTEGER CHECK (capacity IS NULL OR capacity > 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (forum_id, room_code)
);

CREATE TABLE bench (
    bench_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    forum_id BIGINT NOT NULL REFERENCES forum(forum_id) ON DELETE RESTRICT,
    bench_code VARCHAR(50) NOT NULL,
    bench_name VARCHAR(160) NOT NULL,
    bench_type VARCHAR(60),
    valid_from DATE NOT NULL DEFAULT CURRENT_DATE,
    valid_to DATE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK (valid_to IS NULL OR valid_to >= valid_from),
    UNIQUE (forum_id, bench_code, valid_from)
);

CREATE TABLE court_calendar_event (
    calendar_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    forum_id BIGINT NOT NULL REFERENCES forum(forum_id) ON DELETE RESTRICT,
    event_date DATE NOT NULL,
    event_type VARCHAR(40) NOT NULL CHECK (event_type IN
        ('HOLIDAY','COURT_VACATION','WORKING_DAY','SPECIAL_SITTING','OTHER')),
    event_name VARCHAR(180) NOT NULL,
    is_working_day BOOLEAN NOT NULL DEFAULT FALSE,
    notes TEXT,
    UNIQUE (forum_id, event_date, event_name)
);

-- ---------------------------------------------------------------------------
-- 3. PEOPLE, ORGANIZATIONS, LAWYERS, JUDGES AND COURT STAFF
-- PERSON is the common identity record. A person can be a party, lawyer,
-- judge, staff member and/or system user without duplicating their identity.
-- ---------------------------------------------------------------------------

CREATE TABLE person (
    person_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(220) NOT NULL,
    date_of_birth DATE,
    email VARCHAR(254),
    phone VARCHAR(40),
    address TEXT,
    preferred_language VARCHAR(40),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE organization (
    organization_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_name VARCHAR(240) NOT NULL,
    organization_type VARCHAR(80),
    registration_number VARCHAR(100),
    email VARCHAR(254),
    phone VARCHAR(40),
    address TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE lawyer_profile (
    lawyer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id BIGINT NOT NULL UNIQUE REFERENCES person(person_id) ON DELETE RESTRICT,
    law_firm_organization_id BIGINT REFERENCES organization(organization_id) ON DELETE SET NULL,
    profile_status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE'
        CHECK (profile_status IN ('ACTIVE','SUSPENDED','RETIRED','DECEASED','INACTIVE')),
    profile_notes TEXT
);

CREATE TABLE lawyer_registration (
    lawyer_registration_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lawyer_id BIGINT NOT NULL REFERENCES lawyer_profile(lawyer_id) ON DELETE RESTRICT,
    bar_council_name VARCHAR(180) NOT NULL,
    bar_registration_number VARCHAR(100) NOT NULL,
    registration_date DATE,
    verification_status VARCHAR(30) NOT NULL DEFAULT 'PENDING'
        CHECK (verification_status IN ('PENDING','VERIFIED','REJECTED','SUSPENDED','EXPIRED')),
    valid_from DATE,
    valid_to DATE,
    UNIQUE (bar_council_name, bar_registration_number),
    CHECK (valid_to IS NULL OR valid_from IS NULL OR valid_to >= valid_from)
);

CREATE TABLE legal_specialization (
    specialization_code VARCHAR(50) PRIMARY KEY,
    specialization_name VARCHAR(120) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE lawyer_specialization (
    lawyer_id BIGINT NOT NULL REFERENCES lawyer_profile(lawyer_id) ON DELETE RESTRICT,
    specialization_code VARCHAR(50) NOT NULL REFERENCES legal_specialization(specialization_code),
    years_experience NUMERIC(4,1) CHECK (years_experience IS NULL OR years_experience >= 0),
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (lawyer_id, specialization_code)
);

CREATE TABLE judge_profile (
    judge_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id BIGINT NOT NULL UNIQUE REFERENCES person(person_id) ON DELETE RESTRICT,
    judge_code VARCHAR(80) UNIQUE,
    appointment_date DATE,
    retirement_date DATE,
    current_status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE'
        CHECK (current_status IN ('ACTIVE','RETIRED','TRANSFERRED','SUSPENDED','DECEASED')),
    biography TEXT,
    CHECK (retirement_date IS NULL OR appointment_date IS NULL OR retirement_date >= appointment_date)
);

CREATE TABLE judge_posting (
    judge_posting_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    judge_id BIGINT NOT NULL REFERENCES judge_profile(judge_id) ON DELETE RESTRICT,
    forum_id BIGINT NOT NULL REFERENCES forum(forum_id) ON DELETE RESTRICT,
    designation VARCHAR(140) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE,
    posting_order_reference VARCHAR(120),
    CHECK (end_date IS NULL OR end_date >= start_date)
);

CREATE TABLE judge_bench_assignment (
    judge_bench_assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    judge_id BIGINT NOT NULL REFERENCES judge_profile(judge_id) ON DELETE RESTRICT,
    bench_id BIGINT NOT NULL REFERENCES bench(bench_id) ON DELETE RESTRICT,
    role_in_bench VARCHAR(60),
    start_date DATE NOT NULL,
    end_date DATE,
    CHECK (end_date IS NULL OR end_date >= start_date),
    UNIQUE (judge_id, bench_id, start_date)
);

CREATE TABLE court_staff (
    court_staff_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id BIGINT NOT NULL UNIQUE REFERENCES person(person_id) ON DELETE RESTRICT,
    employee_number VARCHAR(100) UNIQUE,
    employment_status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE'
        CHECK (employment_status IN ('ACTIVE','ON_LEAVE','RETIRED','TRANSFERRED','INACTIVE'))
);

CREATE TABLE staff_assignment (
    staff_assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    court_staff_id BIGINT NOT NULL REFERENCES court_staff(court_staff_id) ON DELETE RESTRICT,
    forum_id BIGINT NOT NULL REFERENCES forum(forum_id) ON DELETE RESTRICT,
    staff_role VARCHAR(100) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE,
    reporting_officer_staff_id BIGINT REFERENCES court_staff(court_staff_id) ON DELETE SET NULL,
    CHECK (end_date IS NULL OR end_date >= start_date)
);

-- ---------------------------------------------------------------------------
-- 4. USERS, ROLES, PERMISSIONS AND SCOPED ACCESS
-- A user may have several roles. A role assignment may be global, forum-scoped
-- or case-scoped. The service layer must still enforce record-level access.
-- ---------------------------------------------------------------------------

CREATE TABLE user_account (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id BIGINT UNIQUE REFERENCES person(person_id) ON DELETE RESTRICT,
    username VARCHAR(100) NOT NULL UNIQUE,
    email VARCHAR(254) NOT NULL,
    password_hash TEXT NOT NULL,
    account_status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE'
        CHECK (account_status IN ('ACTIVE','LOCKED','DISABLED','PENDING_VERIFICATION')),
    email_verified_at TIMESTAMPTZ,
    last_login_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uq_user_account_email_lower ON user_account (LOWER(email));

CREATE TABLE app_role (
    role_code VARCHAR(50) PRIMARY KEY,
    role_name VARCHAR(120) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE app_permission (
    permission_code VARCHAR(80) PRIMARY KEY,
    permission_name VARCHAR(160) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE role_permission (
    role_code VARCHAR(50) NOT NULL REFERENCES app_role(role_code) ON DELETE CASCADE,
    permission_code VARCHAR(80) NOT NULL REFERENCES app_permission(permission_code) ON DELETE CASCADE,
    PRIMARY KEY (role_code, permission_code)
);

CREATE TABLE user_role_assignment (
    user_role_assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES user_account(user_id) ON DELETE RESTRICT,
    role_code VARCHAR(50) NOT NULL REFERENCES app_role(role_code),
    forum_id BIGINT REFERENCES forum(forum_id) ON DELETE RESTRICT,
    case_id BIGINT,
    valid_from TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    valid_to TIMESTAMPTZ,
    assigned_by_user_id BIGINT REFERENCES user_account(user_id) ON DELETE SET NULL,
    CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

-- ---------------------------------------------------------------------------
-- 5. PARTIES AND CASE REGISTRATION / LIFECYCLE
-- Party role is case-specific: the same person may be a plaintiff in one case
-- and a defendant/respondent in another.
-- ---------------------------------------------------------------------------

CREATE TABLE party (
    party_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id BIGINT UNIQUE REFERENCES person(person_id) ON DELETE RESTRICT,
    organization_id BIGINT UNIQUE REFERENCES organization(organization_id) ON DELETE RESTRICT,
    party_reference VARCHAR(100) UNIQUE,
    CHECK ((person_id IS NOT NULL AND organization_id IS NULL) OR
           (person_id IS NULL AND organization_id IS NOT NULL))
);

CREATE TABLE case_file (
    case_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cnr VARCHAR(40) UNIQUE,
    case_title VARCHAR(500) NOT NULL,
    case_type_id BIGINT NOT NULL REFERENCES case_type(case_type_id) ON DELETE RESTRICT,
    originating_forum_id BIGINT NOT NULL REFERENCES forum(forum_id) ON DELETE RESTRICT,
    current_forum_id BIGINT NOT NULL REFERENCES forum(forum_id) ON DELETE RESTRICT,
    filing_date DATE NOT NULL,
    registered_date DATE,
    subject_summary TEXT,
    court_value NUMERIC(16,2) CHECK (court_value IS NULL OR court_value >= 0),
    language_code VARCHAR(20),
    is_confidential BOOLEAN NOT NULL DEFAULT FALSE,
    created_by_user_id BIGINT REFERENCES user_account(user_id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (registered_date IS NULL OR registered_date >= filing_date)
);

-- A case may receive a local registration number at more than one forum over
-- its life (for example, after transfer or appellate registration).
ALTER TABLE user_role_assignment
    ADD CONSTRAINT fk_user_role_assignment_case
    FOREIGN KEY (case_id) REFERENCES case_file(case_id) ON DELETE RESTRICT;

CREATE TABLE case_registration (
    case_registration_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT NOT NULL REFERENCES case_file(case_id) ON DELETE RESTRICT,
    forum_id BIGINT NOT NULL REFERENCES forum(forum_id) ON DELETE RESTRICT,
    case_type_id BIGINT NOT NULL REFERENCES case_type(case_type_id) ON DELETE RESTRICT,
    registration_number VARCHAR(80) NOT NULL,
    registration_year SMALLINT NOT NULL CHECK (registration_year BETWEEN 1900 AND 2200),
    registration_date DATE NOT NULL,
    is_current BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (forum_id, case_type_id, registration_year, registration_number)
);
CREATE UNIQUE INDEX uq_case_current_registration ON case_registration(case_id) WHERE is_current;

CREATE TABLE case_status_history (
    case_status_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT NOT NULL REFERENCES case_file(case_id) ON DELETE RESTRICT,
    status_code VARCHAR(40) NOT NULL REFERENCES case_status(status_code) ON DELETE RESTRICT,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    changed_by_user_id BIGINT REFERENCES user_account(user_id) ON DELETE SET NULL,
    remarks TEXT,
    source_reference VARCHAR(120)
);
CREATE INDEX ix_case_status_history_latest ON case_status_history(case_id, changed_at DESC, case_status_history_id DESC);

CREATE TABLE case_party (
    case_party_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT NOT NULL REFERENCES case_file(case_id) ON DELETE RESTRICT,
    party_id BIGINT NOT NULL REFERENCES party(party_id) ON DELETE RESTRICT,
    party_role_code VARCHAR(40) NOT NULL REFERENCES case_party_role(party_role_code),
    party_number INTEGER,
    joined_on DATE NOT NULL DEFAULT CURRENT_DATE,
    ceased_on DATE,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    notes TEXT,
    CHECK (ceased_on IS NULL OR ceased_on >= joined_on),
    UNIQUE (case_id, party_id, party_role_code, joined_on)
);
CREATE INDEX ix_case_party_case ON case_party(case_id);
CREATE INDEX ix_case_party_party ON case_party(party_id);

CREATE TABLE lawyer_representation (
    representation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_party_id BIGINT NOT NULL REFERENCES case_party(case_party_id) ON DELETE RESTRICT,
    lawyer_id BIGINT NOT NULL REFERENCES lawyer_profile(lawyer_id) ON DELETE RESTRICT,
    appointed_on DATE NOT NULL,
    ended_on DATE,
    representation_status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE'
        CHECK (representation_status IN ('ACTIVE','ENDED','WITHDRAWN','SUSPENDED','REVOKED')),
    appointment_reference VARCHAR(140),
    notes TEXT,
    CHECK (ended_on IS NULL OR ended_on >= appointed_on)
);
CREATE INDEX ix_lawyer_representation_active ON lawyer_representation(lawyer_id, ended_on);
CREATE INDEX ix_representation_case_party ON lawyer_representation(case_party_id, ended_on);

CREATE TABLE case_relationship (
    case_relationship_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT NOT NULL REFERENCES case_file(case_id) ON DELETE RESTRICT,
    related_case_id BIGINT NOT NULL REFERENCES case_file(case_id) ON DELETE RESTRICT,
    relationship_type_code VARCHAR(40) NOT NULL
        REFERENCES case_relationship_type(relationship_type_code),
    linked_on DATE NOT NULL DEFAULT CURRENT_DATE,
    notes TEXT,
    CHECK (case_id <> related_case_id),
    UNIQUE (case_id, related_case_id, relationship_type_code)
);

CREATE TABLE case_transfer (
    case_transfer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT NOT NULL REFERENCES case_file(case_id) ON DELETE RESTRICT,
    from_forum_id BIGINT NOT NULL REFERENCES forum(forum_id) ON DELETE RESTRICT,
    to_forum_id BIGINT NOT NULL REFERENCES forum(forum_id) ON DELETE RESTRICT,
    transfer_date DATE NOT NULL,
    transfer_reason TEXT NOT NULL,
    order_reference VARCHAR(140),
    approved_by_user_id BIGINT REFERENCES user_account(user_id) ON DELETE SET NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (from_forum_id <> to_forum_id)
);

-- ---------------------------------------------------------------------------
-- 6. FILING, PETITIONS, SCRUTINY AND DEFECTS
-- Multiple filings/petitions/applications can belong to one case. A first filing
-- may be entered before the case receives a formal case_id (case_id is nullable).
-- ---------------------------------------------------------------------------

CREATE TABLE case_filing (
    filing_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT REFERENCES case_file(case_id) ON DELETE RESTRICT,
    forum_id BIGINT NOT NULL REFERENCES forum(forum_id) ON DELETE RESTRICT,
    filing_type_code VARCHAR(50) NOT NULL REFERENCES filing_type(filing_type_code),
    filing_status_code VARCHAR(40) NOT NULL DEFAULT 'SUBMITTED'
        REFERENCES filing_status(filing_status_code),
    filing_number VARCHAR(100),
    filing_year SMALLINT CHECK (filing_year IS NULL OR filing_year BETWEEN 1900 AND 2200),
    title VARCHAR(400) NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    submitted_by_user_id BIGINT REFERENCES user_account(user_id) ON DELETE SET NULL,
    submitted_by_party_id BIGINT REFERENCES party(party_id) ON DELETE RESTRICT,
    submitted_by_lawyer_id BIGINT REFERENCES lawyer_profile(lawyer_id) ON DELETE RESTRICT,
    filing_channel VARCHAR(30) NOT NULL DEFAULT 'COUNTER'
        CHECK (filing_channel IN ('COUNTER','ONLINE','POST','TRANSFER','OTHER')),
    remarks TEXT,
    CHECK (submitted_by_user_id IS NOT NULL OR submitted_by_party_id IS NOT NULL OR
           submitted_by_lawyer_id IS NOT NULL),
    CHECK ((filing_number IS NULL AND filing_year IS NULL) OR
           (filing_number IS NOT NULL AND filing_year IS NOT NULL)),
    UNIQUE (forum_id, filing_year, filing_number)
);
CREATE INDEX ix_case_filing_case ON case_filing(case_id, submitted_at DESC);

CREATE TABLE petition_detail (
    filing_id BIGINT PRIMARY KEY REFERENCES case_filing(filing_id) ON DELETE RESTRICT,
    petition_number VARCHAR(100),
    petition_kind VARCHAR(100),
    relief_sought TEXT,
    cause_of_action TEXT,
    verification_statement TEXT
);

CREATE TABLE filing_review (
    filing_review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filing_id BIGINT NOT NULL REFERENCES case_filing(filing_id) ON DELETE RESTRICT,
    review_stage VARCHAR(50) NOT NULL CHECK (review_stage IN
        ('INITIAL_SCRUTINY','LEGAL_SCRUTINY','VERIFICATION','REGISTRATION','OTHER')),
    review_result VARCHAR(40) NOT NULL CHECK (review_result IN
        ('PENDING','ACCEPTED','RETURNED_FOR_CORRECTION','REJECTED','WAIVED')),
    reviewed_by_user_id BIGINT REFERENCES user_account(user_id) ON DELETE SET NULL,
    reviewed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    remarks TEXT
);

CREATE TABLE filing_defect (
    defect_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filing_id BIGINT NOT NULL REFERENCES case_filing(filing_id) ON DELETE RESTRICT,
    defect_code VARCHAR(60),
    defect_description TEXT NOT NULL,
    defect_status VARCHAR(30) NOT NULL DEFAULT 'OPEN'
        CHECK (defect_status IN ('OPEN','CURED','WAIVED','REJECTED')),
    identified_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cure_deadline DATE,
    cured_at TIMESTAMPTZ,
    identified_by_user_id BIGINT REFERENCES user_account(user_id) ON DELETE SET NULL,
    resolved_by_user_id BIGINT REFERENCES user_account(user_id) ON DELETE SET NULL,
    resolution_notes TEXT,
    CHECK (cured_at IS NULL OR cured_at >= identified_at)
);
CREATE INDEX ix_filing_defect_open ON filing_defect(defect_status, cure_deadline);

-- ---------------------------------------------------------------------------
-- 7. DOCUMENTS AND VERSION HISTORY
-- File bytes remain outside PostgreSQL; storage_key points to protected storage.
-- ---------------------------------------------------------------------------

CREATE TABLE document (
    document_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT REFERENCES case_file(case_id) ON DELETE RESTRICT,
    document_type_code VARCHAR(50) NOT NULL REFERENCES document_type(document_type_code),
    title VARCHAR(400) NOT NULL,
    description TEXT,
    confidentiality_level VARCHAR(30) NOT NULL DEFAULT 'RESTRICTED'
        CHECK (confidentiality_level IN ('PUBLIC','PARTY_ONLY','RESTRICTED','SEALED')),
    public_visible BOOLEAN NOT NULL DEFAULT FALSE,
    created_by_user_id BIGINT REFERENCES user_account(user_id) ON DELETE SET NULL,
