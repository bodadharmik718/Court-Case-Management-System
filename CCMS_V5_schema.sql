-- ---------------------------------------------------------------------------
-- 8. HEARINGS, CAUSE LISTS, ADJOURNMENTS AND ATTENDANCE
-- Sequence_Number belongs to CAUSE_LIST_ITEM, not to HEARING or CAUSE_LIST.
-- The same hearing may appear in a revised/published cause-list version.
-- ---------------------------------------------------------------------------

CREATE TABLE cause_list (
    cause_list_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    forum_id BIGINT NOT NULL REFERENCES forum(forum_id) ON DELETE RESTRICT,
    bench_id BIGINT REFERENCES bench(bench_id) ON DELETE RESTRICT,
    list_date DATE NOT NULL,
    list_type VARCHAR(50) NOT NULL DEFAULT 'DAILY',
    session_name VARCHAR(100) NOT NULL DEFAULT 'GENERAL',
    version_number INTEGER NOT NULL DEFAULT 1 CHECK (version_number > 0),
    publication_status VARCHAR(30) NOT NULL DEFAULT 'DRAFT'
        CHECK (publication_status IN ('DRAFT','PUBLISHED','SUPERSEDED','CANCELLED')),
    published_at TIMESTAMPTZ,
    created_by_user_id BIGINT REFERENCES user_account(user_id) ON DELETE SET NULL,
    UNIQUE (forum_id, list_date, list_type, session_name, version_number)
);

CREATE TABLE hearing (
    hearing_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT NOT NULL REFERENCES case_file(case_id) ON DELETE RESTRICT,
    forum_id BIGINT NOT NULL REFERENCES forum(forum_id) ON DELETE RESTRICT,
    bench_id BIGINT REFERENCES bench(bench_id) ON DELETE RESTRICT,
    courtroom_id BIGINT REFERENCES courtroom(courtroom_id) ON DELETE SET NULL,
    hearing_date DATE NOT NULL,
    start_time TIME,
    end_time TIME,
    actual_start_time TIMESTAMPTZ,
    actual_end_time TIMESTAMPTZ,
    hearing_purpose VARCHAR(120),
    hearing_status VARCHAR(30) NOT NULL DEFAULT 'SCHEDULED'
        CHECK (hearing_status IN ('SCHEDULED','IN_PROGRESS','HEARD','ADJOURNED','CANCELLED','NOT_TAKEN_UP')),
    proceeding_summary TEXT,
    outcome_summary TEXT,
    next_steps TEXT,
    rescheduled_from_hearing_id BIGINT REFERENCES hearing(hearing_id) ON DELETE SET NULL,
    created_by_user_id BIGINT REFERENCES user_account(user_id) ON DELETE SET NULL,
    CHECK (start_time IS NULL OR end_time IS NULL OR end_time > start_time),
    CHECK (actual_start_time IS NULL OR actual_end_time IS NULL OR actual_end_time >= actual_start_time)
);
CREATE INDEX ix_hearing_date_forum ON hearing(forum_id, hearing_date, start_time);
CREATE INDEX ix_hearing_case_date ON hearing(case_id, hearing_date DESC);

CREATE TABLE cause_list_item (
    cause_list_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
