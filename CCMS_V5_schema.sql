CREATE VIEW v_case_current_status AS
SELECT
    c.case_id,
    c.cnr,
    c.case_title,
    c.case_type_id,
    ct.case_type_code,
    ct.case_type_name,
    cc.category_code,
    cc.category_name,
    c.originating_forum_id,
    c.current_forum_id,
    f.forum_name AS current_forum_name,
    c.filing_date,
    c.registered_date,
    COALESCE(latest.status_code, 'FILED') AS current_status_code,
    COALESCE(cs.status_name, 'Filed') AS current_status_name,
    latest.changed_at AS status_last_changed_at,
    latest.remarks AS latest_status_remarks
FROM case_file c
JOIN case_type ct ON ct.case_type_id = c.case_type_id
JOIN case_category cc ON cc.category_code = ct.category_code
JOIN forum f ON f.forum_id = c.current_forum_id
LEFT JOIN LATERAL (
    SELECT h.status_code, h.changed_at, h.remarks
    FROM case_status_history h
    WHERE h.case_id = c.case_id
    ORDER BY h.changed_at DESC, h.case_status_history_id DESC
    LIMIT 1
) latest ON TRUE
LEFT JOIN case_status cs ON cs.status_code = latest.status_code;

CREATE VIEW v_pending_case_dashboard AS
SELECT
    vcs.*,
    (CURRENT_DATE - vcs.filing_date) AS days_since_filing,
    CASE
      WHEN CURRENT_DATE - vcs.filing_date <= 90 THEN '0-90 days'
      WHEN CURRENT_DATE - vcs.filing_date <= 365 THEN '91-365 days'
      WHEN CURRENT_DATE - vcs.filing_date <= 1095 THEN '1-3 years'
      ELSE 'Over 3 years'
    END AS case_age_bucket
FROM v_case_current_status vcs
JOIN case_status cs ON cs.status_code = vcs.current_status_code
WHERE cs.is_terminal = FALSE;

CREATE VIEW v_upcoming_hearings AS
