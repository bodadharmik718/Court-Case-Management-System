CREATE VIEW v_lawyer_active_case_load AS
SELECT
    lp.lawyer_id,
    p.full_name AS lawyer_name,
    COUNT(DISTINCT cp.case_id) FILTER (
        WHERE lr.ended_on IS NULL
          AND lr.representation_status = 'ACTIVE'
          AND vcs.current_status_code IS NOT NULL
          AND vcs.current_status_code NOT IN ('DISPOSED','DISMISSED','WITHDRAWN','CLOSED')
    ) AS active_case_count,
    COUNT(DISTINCT cp.case_id) AS total_cases_ever_represented
FROM lawyer_profile lp
JOIN person p ON p.person_id = lp.person_id
LEFT JOIN lawyer_representation lr ON lr.lawyer_id = lp.lawyer_id
LEFT JOIN case_party cp ON cp.case_party_id = lr.case_party_id
LEFT JOIN v_case_current_status vcs ON vcs.case_id = cp.case_id
GROUP BY lp.lawyer_id, p.full_name;

